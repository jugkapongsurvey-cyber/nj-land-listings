/* โหลดสไตล์ชีตที่ไม่ได้ใช้กับสิ่งที่เห็นทันที แบบไม่บล็อกการวาดหน้า
 *
 * ทำไมต้องมี: `<link rel="stylesheet">` ทุกอันบล็อกการวาดหน้าจนกว่าจะโหลดเสร็จ
 * หน้าแรกโหลดสไตล์ชีต 12 ไฟล์ แต่มีหลายไฟล์ที่ใช้กับ **ของที่ JS สร้างทีหลัง**
 * (ปุ่มบันทึก/เทียบแปลงในการ์ด · ป้ายระดับตรวจสอบ · กล่องแชท · แถบคุกกี้)
 * Lighthouse (mobile) วัดได้ว่าไฟล์กลุ่มนี้ถ่วงการวาดหน้าราว 160 ms
 *
 * วิธีแก้: หน้าเว็บประกาศเป็น `rel="preload" as="style" data-njcss` ซึ่ง
 * **ดาวน์โหลดทันทีแต่ยังไม่เอามาใช้** แล้วไฟล์นี้สลับเป็น `rel="stylesheet"` ให้
 *
 * ⚠️ ไฟล์นี้อยู่ใน CORE_JS ของ build/pages.js จึงรันเป็นสคริปต์ **ตัวแรกของทุกหน้า**
 *    (แบบ defer · เรียงตามลำดับ) สไตล์จึงถูกเปิดใช้ก่อนสคริปต์ที่สร้าง element เหล่านั้นเสมอ
 *    **ห้ามย้ายไปไว้ท้ายรายการ** ไม่งั้นจะเห็นของที่ยังไม่มีสไตล์แวบหนึ่ง
 *
 * ⚠️ ห้ามกลับไปใช้ `onload="this.rel='stylesheet'"` บนแท็ก link เด็ดขาด —
 *    กติกาของรีโปนี้ห้าม `on*=` ในหน้าที่เสิร์ฟ (ดู CLAUDE.md หัวข้อ CSP)
 *    และ `a11y.test.js` / `build/lint.js` ตรวจไว้
 *
 * ⚠️ ต้องมี <noscript> คู่กันในหน้าเสมอ — ปิด JS แล้วต้องยังได้สไตล์ครบ
 *
 * ⚠️ **สไตล์ชีตที่ใช้กับ HTML ที่อยู่ในหน้าอยู่แล้ว ห้ามทำเป็น preload** —
 *    build/lazycss.js เลือกให้เฉพาะหน้าที่ไม่มีคลาสของไฟล์นั้นอยู่ในมาร์กอัปเลย
 */
(function (d) {
  'use strict';
  var links = d.querySelectorAll('link[rel="preload"][as="style"][data-njcss]');
  for (var i = 0; i < links.length; i++) {
    links[i].rel = 'stylesheet';
  }
})(document);
